import { Address, AddressInput } from './address.model';

/**
 * Employee as returned by the API (`EmployeeListDto`).
 *
 * Relations:
 *  - Department (N:1): referenced by `departmentId`, name denormalized as `departmentName`.
 *  - Address (1:N): embedded in `addresses`.
 *
 * Dates are ISO strings: `yyyy-MM-dd` for DateOnly fields, ISO 8601 for `createdAt` / `updatedAt`.
 */
export interface Employee {
  id: number;
  employeeNumber: string;
  identityNumber: string;
  firstName: string;
  lastName: string;
  email: string;
  phoneNumber: string | null;
  dateOfBirth: string;
  hireDate: string;
  departmentId: number;
  departmentName: string;
  jobTitle: string | null;
  isActive: boolean;
  createdAt: string;
  updatedAt: string | null;
  addresses: Address[];
}

/**
 * Request payload for creating (POST) and fully updating (PUT) an employee.
 * `employeeNumber` is generated by the backend and must not be sent.
 */
export interface EmployeeInput {
  identityNumber: string;
  firstName: string;
  lastName: string;
  email: string;
  phoneNumber?: string | null;
  dateOfBirth: string;
  hireDate: string;
  departmentId: number;
  jobTitle?: string | null;
  isActive: boolean;
  addresses: AddressInput[];
}
